// TexEscape escapes special LaTeX characters.
func TexEscape(s string) string {
	r := strings.NewReplacer(
		"_", `\_`,
		"%", `\%`,
		"&", `\&`,
		"#", `\#`,
		"$", `\$`,
		"{", `\{`,
		"}", `\}`,
		"~", `\textasciitilde{}`,
	)
	return r.Replace(s)
}

// ShortModelTexName shortens a provider/model string for captions (e.g. ollama/qwen2.5:3b-instruct).
func ShortModelTexName(s string) string {
	parts := strings.SplitN(s, "/", 2)
	name := parts[len(parts)-1]
	name = strings.ReplaceAll(name, ":latest", "")
	return TexEscape(name)
}

// LevelTagShort maps full level names to short labels (L1, L2, L3).
func LevelTagShort(s string) string {
	switch s {
	case "L1-diagnostic":
		return "L1"
	case "L2-repair":
		return "L2"
	case "L3-multi-step":
		return "L3"
	}
	return s
}

// FmtSci formats very small p-values in scientific notation for LaTeX.
func FmtSci(v float64) string {
	if v == 0 {
		return "$< 10^{-15}$"
	}
	if v >= 0.001 {
		return fmt.Sprintf("%.4f", v)
	}
	exp := int(math.Floor(math.Log10(math.Abs(v))))
	mantissa := v / math.Pow(10, float64(exp))
	return fmt.Sprintf("$%.2f{\\times}10^{%d}$", mantissa, exp)
}

// FmtDelta formats a signed delta for tables.
func FmtDelta(v float64) string {
	if v > 0 {
		return fmt.Sprintf("+%.4f", v)
	}
	if v < 0 {
		return fmt.Sprintf("%.4f", v)
	}
	return "0"
}

// FmtDeltaPct formats a delta as a percentage (ESR scale 0–1).
func FmtDeltaPct(v float64) string {
	pct := v * 100
	if pct > 0 {
		return fmt.Sprintf("+%.1f", pct)
	}
	if pct < 0 {
		return fmt.Sprintf("%.1f", pct)
	}
	return "0.0"
}

// FmtSig maps significance strings to LaTeX macro calls.
func FmtSig(s string) string {
	switch s {
	case "***":
		return `\sigHigh{***}`
	case "**":
		return `\sigMed{**}`
	case "*":
		return `\sigLow{*}`
	case "n.s.":
		return `n.s.`
	default:
		return "---"
	}
}

// MetricIsHolmTested returns true if the metric row used Holm–Bonferroni correction.
func MetricIsHolmTested(m MetricComparison) bool {
	return m.CorrectionMethod != "" && m.CorrectionMethod != "n/a"
}

// FilterHolmTestedMetrics keeps only statistically tested aggregate rows.
func FilterHolmTestedMetrics(ms []MetricComparison) []MetricComparison {
	var out []MetricComparison
	for _, m := range ms {
		if MetricIsHolmTested(m) {
			out = append(out, m)
		}
	}
	return out
}

// FilterScalarMetrics keeps descriptive-only rows (no per-run vector).
func FilterScalarMetrics(ms []MetricComparison) []MetricComparison {
	var out []MetricComparison
	for _, m := range ms {
		if !MetricIsHolmTested(m) {
			out = append(out, m)
		}
	}
	return out
}

// CountTaskComparisonDelta counts wins/ties/losses for model A vs B (dir: 1, 0, -1 by Delta sign).
func CountTaskComparisonDelta(tc []TaskComparison, dir int) int {
	n := 0
	for _, t := range tc {
		switch {
		case dir > 0 && t.Delta > 0:
			n++
		case dir < 0 && t.Delta < 0:
			n++
		case dir == 0 && t.Delta == 0:
			n++
		}
	}
	return n
}

