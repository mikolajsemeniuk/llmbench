// RenderCompareLatex writes LaTeX tables for a compare JSON payload to w.
func RenderCompareLatex(w io.Writer, cr CompareReport) error {
	funcMap := template.FuncMap{
		"pct":       func(v float64) string { return fmt.Sprintf("%.1f", v*100) },
		"f2":        func(v float64) string { return fmt.Sprintf("%.2f", v) },
		"f3":        func(v float64) string { return fmt.Sprintf("%.3f", v) },
		"f4":        func(v float64) string { return fmt.Sprintf("%.4f", v) },
		"sci":       FmtSci,
		"delta":     FmtDelta,
		"deltaPct":  FmtDeltaPct,
		"sig":       FmtSig,
		"esc":       TexEscape,
		"shortName": ShortModelTexName,
		"levelTag":  LevelTagShort,
		"isTested":  MetricIsHolmTested,
		"add":       func(a, b int) int { return a + b },
		"half":      func(tc []TaskComparison) int { return len(tc) / 2 },
		"taskAt":    func(tc []TaskComparison, i int) TaskComparison { return tc[i] },
		"lt":        func(a, b int) bool { return a < b },
		"seq": func(n int) []int {
			s := make([]int, n)
			for i := range s {
				s[i] = i
			}
			return s
		},
		"wins":   func(tc []TaskComparison) int { return CountTaskComparisonDelta(tc, 1) },
		"ties":   func(tc []TaskComparison) int { return CountTaskComparisonDelta(tc, 0) },
		"losses": func(tc []TaskComparison) int { return CountTaskComparisonDelta(tc, -1) },
		"tested":  FilterHolmTestedMetrics,
		"scalars": FilterScalarMetrics,
	}

	tpl, err := template.New("latex").Funcs(funcMap).Parse(CompareLatexTemplate)
	if err != nil {
		return err
	}
	return tpl.Execute(w, cr)
}
